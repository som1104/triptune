-- 초대 링크로 처음 들어온 사람에게는 아직 세션이 없다.
-- 익명 로그인은 "여행에 참여하기"를 누를 때 비로소 시작되므로, /join 화면을
-- 그리는 서버 요청은 anon 역할로 나간다. 그런데 get_trip_invite_info 의 실행
-- 권한이 authenticated 에만 있어서, 세션이 없는 브라우저로 초대 링크를 열면
-- 함수 호출이 권한 오류로 떨어지고 화면은 "초대 링크를 찾을 수 없어요."가 됐다.
--
-- 이 함수는 security definer 이고, 비밀 초대 토큰을 아는 사람에게 초대 화면에
-- 필요한 것만 돌려준다 (여행 이름·목적지·시기·인원 수·이미 참여했는지).
-- 토큰 없이는 한 줄도 나오지 않으므로, anon 에게 실행 권한을 주는 것이 원래
-- 의도한 동작이다. 테이블 자체의 RLS 는 그대로 두고 함수 권한만 넓힌다.
grant execute on function get_trip_invite_info(text) to anon;
